// latency_tb - measure UberDDR3 read latency in simulation, against the Micron
// DDR3 model, at the strudelworks clock configuration.
//
// This answers the derisk question without hardware.  rtl/latency_probe.sv does
// the same measurement on the real board; this one runs in about a minute and
// can separate access patterns that the hardware probe can only lump together.
//
// Four patterns, chosen to isolate each latency term:
//
//   PAGE_HIT   consecutive columns in one row of one bank.  Best case: no
//              ACTIVATE, no PRECHARGE, pure pipeline latency.
//   ROW_MISS   same bank every time, a different row every time.  Worst case:
//              PRECHARGE then ACTIVATE before every read, and because it is the
//              same bank each time none of it can overlap.
//   BANK_ROT   a different row every time, but rotating through all 8 banks.
//              Same number of row misses as ROW_MISS - the only difference is
//              which bank they land in.  This pair was added to size the
//              address-mapping lever: if spreading accesses across banks let
//              PRECHARGE/ACTIVATE overlap, BANK_ROT would beat ROW_MISS and it
//              would be worth choosing the Apple-address-to-Wishbone-address map
//              to maximise bank changes.  MEASURED RESULT: they are identical,
//              12 cycles both.  The lever does not exist - UberDDR3's command
//              slotting already hides tRP and tRCD.  Do not spend effort on the
//              address map for latency reasons.  Kept as a regression: if a
//              future controller change makes these diverge, the lever is back.
//   RANDOM     LFSR over the whole space; what a real access stream looks like.
//
// Latency is counted from the cycle the request is first presented (stb high) to
// the cycle ack is seen, inclusive, so it includes any stall.  That is
// deliberate: a refresh that stalls the bus costs the 6502 exactly as much as
// pipeline depth does.
//
// CAVEAT ON DENSITY.  UberDDR3 ships only the 8 Gb Micron parameter set, so the
// modelled device is 8 Gb where the Au's is 2 Gb (MT41K128M16JT-125).  Same
// speed bin (sg125), same x16 organisation, same CL/CWL/tRCD/tRP - so every
// number below is exact EXCEPT refresh, where the model's tRFC is 350 ns against
// the real part's 160 ns.  Refresh-collision outliers here are therefore roughly
// twice as bad as the real board's.  Scale by 160/350 to estimate, or drop a
// 2048Mb_ddr3_parameters.vh from Micron into the testbench directory to measure
// it directly.
//////////////////////////////////////////////////////////////////////////////////

module latency_tb;

`include "sim_defines.vh"
`ifdef den8192Mb
    `include "8192Mb_ddr3_parameters.vh"
`else
    ERROR: expected den8192Mb from sim_defines.vh
`endif

    // ---- strudelworks configuration -------------------------------------
    // These must track rtl/clk_gen.v and rtl/ddr3_wrapper.sv.
    localparam CONTROLLER_CLK_PERIOD = 10_000;  // ps -> 100 MHz
    localparam DDR3_CLK_PERIOD       =  2_500;  // ps -> 400 MHz, DDR3-800
    localparam BYTE_LANES            = 2;       // x16
    localparam ODELAY_SUPPORTED      = 0;       // bank 15 is an HR bank
    localparam AUX_WIDTH             = 4;
    localparam BIST_MODE             = 0;       // skip the built-in test; we are
                                                // measuring, not qualifying

    // SDRAM_CAPACITY selects the controller's tRFC and NOTHING else - it is used
    // at exactly one place in ddr3_controller.v, the tRFC localparam.  That makes
    // the density mismatch tractable: the refresh stall we are measuring is
    // generated by the CONTROLLER (it holds the bus for its own computed tRFC),
    // not by the model.  So running the controller at the real part's 2 Gb while
    // the model stays 8 Gb reproduces the real stall exactly.
    //
    //   +define+MODEL_DENSITY  - 8 Gb (5).  Self-consistent with the model; the
    //                            model raises no complaints, but tRFC is 350 ns
    //                            where the Au's part is 160, so refresh outliers
    //                            are ~2x pessimistic.
    //   default                - 2 Gb (3).  Matches the Au's MT41K128M16JT-125.
    //                            The 8 Gb model will report tRFC violations; that
    //                            is EXPECTED and is the density mismatch talking,
    //                            not a controller bug.  Data is still checked, so
    //                            if the violation actually corrupted a read the
    //                            error count would say so.
`ifdef MODEL_DENSITY
    localparam SDRAM_CAPACITY        = 5;       // 8 Gb, matches the model
`else
    localparam SDRAM_CAPACITY        = 3;       // 2 Gb, matches the real part
`endif

    localparam WB_DATA_BITS = 8*BYTE_LANES*4*2;                 // 128
    localparam WB_SEL_BITS  = WB_DATA_BITS/8;                   // 16
    localparam WB_ADDR_BITS = ROW_BITS + COL_BITS + BA_BITS - 3;

    // i_wb_addr is {row, bank, col[COL_BITS-1:3]}
    localparam COL_FIELD_BITS = COL_BITS - 3;
    localparam BANK_LSB       = COL_FIELD_BITS;
    localparam ROW_LSB        = COL_FIELD_BITS + BA_BITS;

    localparam integer N_MEASURED = 500;   // reads per pattern
    localparam integer N_PATTERNS = 5;

    // ---- clocks and reset ------------------------------------------------
    reg i_controller_clk = 1, i_ddr3_clk = 1, i_ref_clk = 1, i_ddr3_clk_90 = 1;
    reg i_rst_n = 0;

    always #(CONTROLLER_CLK_PERIOD/2) i_controller_clk = !i_controller_clk;
    always #(DDR3_CLK_PERIOD/2)       i_ddr3_clk       = !i_ddr3_clk;
    always #2500                      i_ref_clk        = !i_ref_clk;  // 200 MHz
    initial begin
        #(DDR3_CLK_PERIOD/4);
        forever #(DDR3_CLK_PERIOD/2) i_ddr3_clk_90 = !i_ddr3_clk_90;
    end

    // ---- DUT interface ---------------------------------------------------
    reg                     i_wb_cyc = 0, i_wb_stb = 0, i_wb_we = 0;
    reg  [WB_ADDR_BITS-1:0] i_wb_addr = 0;
    reg  [WB_DATA_BITS-1:0] i_wb_data = 0;
    reg  [WB_SEL_BITS-1:0]  i_wb_sel  = {WB_SEL_BITS{1'b1}};
    reg  [AUX_WIDTH-1:0]    i_aux = 0;
    wire                    o_wb_stall, o_wb_ack, o_wb_err;
    wire [WB_DATA_BITS-1:0] o_wb_data;
    wire [AUX_WIDTH-1:0]    o_aux;
    wire                    o_calib_complete;

    wire [0:0] ck_en, cs_n, odt, o_ddr3_clk_p, o_ddr3_clk_n;
    wire ras_n, cas_n, we_n, reset_n;
    wire [ROW_BITS-1:0] addr;
    wire [BA_BITS-1:0]  ba_addr;
    wire [BYTE_LANES-1:0] ddr3_dm;
    wire [(8*BYTE_LANES)-1:0] dq;
    wire [BYTE_LANES-1:0] dqs, dqs_n;

    ddr3_top #(
        .CONTROLLER_CLK_PERIOD (CONTROLLER_CLK_PERIOD),
        .DDR3_CLK_PERIOD       (DDR3_CLK_PERIOD),
        .ROW_BITS              (ROW_BITS),
        .COL_BITS              (COL_BITS),
        .BA_BITS               (BA_BITS),
        .BYTE_LANES            (BYTE_LANES),
        .AUX_WIDTH             (AUX_WIDTH),
        .MICRON_SIM            (1),
        .ODELAY_SUPPORTED      (ODELAY_SUPPORTED),
        .SECOND_WISHBONE       (0),
        .ECC_ENABLE            (0),
        .WB_ERROR              (0),
        .BIST_MODE             (BIST_MODE),
        .SELF_REFRESH          (0),
        .DUAL_RANK_DIMM        (0),
        .DLL_OFF               (0),
        .SPEED_BIN             (3),
        .SDRAM_CAPACITY        (SDRAM_CAPACITY),
        .REFRESH_GATE          (1)   // milestone-2 patch enabled
    ) dut (
        .i_controller_clk (i_controller_clk),
        .i_ddr3_clk       (i_ddr3_clk),
        .i_ref_clk        (i_ref_clk),
        .i_ddr3_clk_90    (i_ddr3_clk_90),
        .i_rst_n          (i_rst_n),

        .i_wb_cyc  (i_wb_cyc),
        .i_wb_stb  (i_wb_stb),
        .i_wb_we   (i_wb_we),
        .i_wb_addr (i_wb_addr),
        .i_wb_data (i_wb_data),
        .i_wb_sel  (i_wb_sel),
        .i_aux     (i_aux),
        .o_wb_stall(o_wb_stall),
        .o_wb_ack  (o_wb_ack),
        .o_wb_err  (o_wb_err),
        .o_wb_data (o_wb_data),
        .o_aux     (o_aux),

        .i_wb2_cyc (1'b0), .i_wb2_stb (1'b0), .i_wb2_we (1'b0),
        .i_wb2_addr(7'b0), .i_wb2_data(32'b0), .i_wb2_sel(4'b0),
        .o_wb2_stall(), .o_wb2_ack(), .o_wb2_data(),

        .o_ddr3_clk_p  (o_ddr3_clk_p),
        .o_ddr3_clk_n  (o_ddr3_clk_n),
        .o_ddr3_cke    (ck_en),
        .o_ddr3_cs_n   (cs_n),
        .o_ddr3_odt    (odt),
        .o_ddr3_ras_n  (ras_n),
        .o_ddr3_cas_n  (cas_n),
        .o_ddr3_we_n   (we_n),
        .o_ddr3_reset_n(reset_n),
        .o_ddr3_addr   (addr),
        .o_ddr3_ba_addr(ba_addr),
        .io_ddr3_dq    (dq),
        .io_ddr3_dqs   (dqs),
        .io_ddr3_dqs_n (dqs_n),
        .o_ddr3_dm     (ddr3_dm),

        .o_calib_complete   (o_calib_complete),
        .o_debug1           (),
        .i_user_self_refresh(1'b0),
        .i_refresh_ok       (refresh_ok),
        .uart_tx            ()
    );

    // x16 device - sim_defines.vh defines `x16 for the TWO_LANES_x8 case.
    ddr3 #(.DLL_OFF(0)) ddr3_dev (
        .rst_n  (reset_n),
        .ck     (o_ddr3_clk_p[0]),
        .ck_n   (o_ddr3_clk_n[0]),
        .cke    (ck_en[0]),
        .cs_n   (cs_n[0]),
        .ras_n  (ras_n),
        .cas_n  (cas_n),
        .we_n   (we_n),
        .dm_tdqs(ddr3_dm),
        .ba     (ba_addr),
        .addr   (addr),
        .dq     (dq),
        .dqs    (dqs),
        .dqs_n  (dqs_n),
        .tdqs_n (),
        .odt    (odt[0])
    );

    // ---- address patterns ------------------------------------------------
    localparam [2:0] P_PAGE_HIT = 0, P_ROW_MISS = 1, P_BANK_ROT = 2, P_RANDOM = 3,
                     P_GATED    = 4;

    // GATED uses the same scattered addresses as RANDOM, but models what the real
    // design does: between accesses the bus spends a cycle served from the line
    // buffer, during which DDR3 is idle and refresh_ok is asserted.
    //
    // One IIgs bus cycle is 357 ns = ~35 controller clocks.  refresh_ok is raised
    // only for the FIRST few of those, so any refresh it triggers (PRE_REFRESH
    // drain + tRP + tRFC, about 23 clocks on the Au's 2 Gb part) has finished
    // before the cycle ends.  Real bus logic must do the same: assert at the
    // START of a known-free cycle, not part way through.
    //
    // This pair of numbers is load-bearing, and the test is sensitive to it.
    // Run with +define+MODEL_DENSITY (8 Gb, tRFC 350 ns) and the refresh sequence
    // grows to ~42 clocks, no longer fits in 35, overruns into the next access,
    // and GATED goes from 0-over-budget to 50-of-500.  That is the constraint
    // working as designed, not a regression: the rule is "assert refresh_ok only
    // when at least tRFC + ~7 clocks of idle remain", and a bigger device needs a
    // bigger window.  See docs/DERISK.md.
    localparam integer IIGS_CYCLE_CLKS = 35;
    localparam integer GATE_ASSERT_CLKS = 6;

    reg [31:0] lfsr_state;
    reg        refresh_ok = 1'b0;

    function [WB_ADDR_BITS-1:0] make_addr(input [2:0] pat, input integer i);
        reg [ROW_BITS-1:0]       row;
        reg [BA_BITS-1:0]        bank;
        reg [COL_FIELD_BITS-1:0] col;
        begin
            case (pat)
                // one row, one bank, walk the columns
                P_PAGE_HIT: begin
                    row  = 16'h0100;
                    bank = 3'd0;
                    col  = i[COL_FIELD_BITS-1:0];
                end
                // one bank, a new row every access: nothing can overlap
                P_ROW_MISS: begin
                    row  = 16'h0200 + i[ROW_BITS-1:0];
                    bank = 3'd0;
                    col  = 0;
                end
                // a new row every access, but spread over all 8 banks
                P_BANK_ROT: begin
                    row  = 16'h0400 + i[ROW_BITS-1:0];
                    bank = i[2:0];
                    col  = 0;
                end
                // scattered - RANDOM and GATED share this
                default: begin
                    row  = 16'h0800 + lfsr_state[ROW_BITS-1:0];
                    bank = lfsr_state[18:16];
                    col  = lfsr_state[COL_FIELD_BITS-1:0];
                end
            endcase
            make_addr = {row, bank, col};
        end
    endfunction

    task step_lfsr;
        begin
            lfsr_state = lfsr_state[0] ? ((lfsr_state >> 1) ^ 32'hD000_0001)
                                       : (lfsr_state >> 1);
        end
    endtask

    function [WB_DATA_BITS-1:0] pattern_of(input [WB_ADDR_BITS-1:0] a);
        integer w;
        begin
            for (w = 0; w < WB_DATA_BITS/32; w = w + 1)
                pattern_of[w*32 +: 32] = {{(32-WB_ADDR_BITS){1'b0}}, a}
                                       ^ (32'hA5A5_0000 + w);
        end
    endfunction

    // ---- bus tasks -------------------------------------------------------
    integer cyc_count;
    reg     done_flag;

    // Untimed write.  Used only to seed the region so reads can be checked.
    task do_write(input [WB_ADDR_BITS-1:0] a);
        begin
            @(negedge i_controller_clk);
            i_wb_cyc = 1; i_wb_stb = 1; i_wb_we = 1;
            i_wb_addr = a; i_wb_data = pattern_of(a);
            done_flag = 0;
            while (!done_flag) begin
                @(posedge i_controller_clk);
                if (!o_wb_stall) done_flag = 1;
            end
            @(negedge i_controller_clk);
            i_wb_stb = 0;
            done_flag = 0;
            while (!done_flag) begin
                @(posedge i_controller_clk);
                if (o_wb_ack) done_flag = 1;
            end
        end
    endtask

    // Timed read.  One outstanding request only - unloaded latency is the
    // question; pipelining more would measure throughput instead.
    task do_timed_read(input [WB_ADDR_BITS-1:0] a, output integer cycles);
        begin
            @(negedge i_controller_clk);
            i_wb_cyc = 1; i_wb_stb = 1; i_wb_we = 0; i_wb_addr = a;
            cyc_count = 0;
            done_flag = 0;
            while (!done_flag) begin
                @(posedge i_controller_clk);
                cyc_count = cyc_count + 1;
                if (!o_wb_stall) done_flag = 1;
            end
            @(negedge i_controller_clk);
            i_wb_stb = 0;
            done_flag = 0;
            while (!done_flag) begin
                @(posedge i_controller_clk);
                cyc_count = cyc_count + 1;
                if (o_wb_ack) done_flag = 1;
            end
            if (o_wb_data !== pattern_of(a)) begin
                $display("DATA MISMATCH at addr %h: got %h want %h",
                         a, o_wb_data, pattern_of(a));
                errors = errors + 1;
            end
            cycles = cyc_count;
        end
    endtask

    // ---- run -------------------------------------------------------------
    integer errors;
    integer p, i, c;
    integer lo, hi, total;
    integer over_gs, over_ii;
    integer hist [0:63];
    integer h;
    reg [WB_ADDR_BITS-1:0] a;
    reg [8*10-1:0] pname;

    // The IIgs window is ~180 ns and the legacy window ~490 ns; at a 10 ns
    // controller clock that is 18 and 49 cycles.
    localparam integer GS_BUDGET_CYCLES     = 18;
    localparam integer LEGACY_BUDGET_CYCLES = 49;

    initial begin
        errors = 0;
        lfsr_state = 32'h1234_5678;

        i_rst_n = 0;
        repeat (20) @(posedge i_controller_clk);
        i_rst_n = 1;

        $display("waiting for calibration...");
        wait (o_calib_complete === 1'b1);
        $display("calibration complete at %0t ps", $time);
        repeat (50) @(posedge i_controller_clk);

        for (p = 0; p < N_PATTERNS; p = p + 1) begin
            case (p)
                P_PAGE_HIT: pname = "PAGE_HIT";
                P_ROW_MISS: pname = "ROW_MISS";
                P_BANK_ROT: pname = "BANK_ROT";
                P_RANDOM:   pname = "RANDOM";
                default:    pname = "GATED";
            endcase

            // seed pass - untimed, so the timed pass can verify data
            lfsr_state = 32'h1234_5678;
            for (i = 0; i < N_MEASURED; i = i + 1) begin
                a = make_addr(p[2:0], i);
                do_write(a);
                if (p >= P_RANDOM) step_lfsr;
            end

            // measured pass
            lfsr_state = 32'h1234_5678;
            lo = 1000; hi = 0; total = 0;
            over_gs = 0; over_ii = 0;
            for (h = 0; h < 64; h = h + 1) hist[h] = 0;

            for (i = 0; i < N_MEASURED; i = i + 1) begin
                a = make_addr(p[2:0], i);
                if (p == P_GATED) begin
                    // an idle bus cycle: DDR3 free, refresh invited at the start
                    refresh_ok = 1'b1;
                    repeat (GATE_ASSERT_CLKS) @(posedge i_controller_clk);
                    refresh_ok = 1'b0;
                    repeat (IIGS_CYCLE_CLKS - GATE_ASSERT_CLKS)
                        @(posedge i_controller_clk);
                end
                do_timed_read(a, c);
                if (c < lo) lo = c;
                if (c > hi) hi = c;
                total = total + c;
                if (c < 64) hist[c] = hist[c] + 1;
                if (c > GS_BUDGET_CYCLES)     over_gs = over_gs + 1;
                if (c > LEGACY_BUDGET_CYCLES) over_ii = over_ii + 1;
                if (p >= P_RANDOM) step_lfsr;
            end

            $display("");
            $display("=== %0s (%0d reads) ===", pname, N_MEASURED);
            $display("  min  %0d cycles = %0d ns", lo, lo*10);
            $display("  mean %0d cycles = %0d ns", total/N_MEASURED,
                     (total*10)/N_MEASURED);
            $display("  max  %0d cycles = %0d ns", hi, hi*10);
            $display("  over IIgs budget (>%0d cy): %0d of %0d",
                     GS_BUDGET_CYCLES, over_gs, N_MEASURED);
            $display("  over legacy budget (>%0d cy): %0d of %0d",
                     LEGACY_BUDGET_CYCLES, over_ii, N_MEASURED);
            $write("  histogram:");
            for (h = 0; h < 64; h = h + 1)
                if (hist[h] != 0) $write(" %0d:%0d", h, hist[h]);
            $display("");
        end

        $display("");
        $display("data errors: %0d", errors);
        $display("NOTE: modelled device is 8 Gb (tRFC 350 ns); the Au's is 2 Gb");
        $display("      (tRFC 160 ns), so refresh outliers here are pessimistic.");
        $finish;
    end

    // Safety net - never let a protocol mistake hang a batch run.
    initial begin
        // 1.5 ms: the four ungated patterns need ~400 us, and GATED adds
        // another ~175 us of deliberate idle time (500 reads x 35 clocks of
        // simulated bus cycle).
        #1_500_000_000;
        $display("TIMEOUT");
        $finish;
    end

endmodule
