# Simulate UberDDR3 read latency at the strudelworks configuration, using the
# Micron DDR3 model and UberDDR3's behavioural Xilinx primitive models.
#
# Needs iverilog only - no Vivado, no hardware.
#
#   run_latency_tb.sh                  controller at 2 Gb tRFC = the real Au part
#   run_latency_tb.sh --model-density  controller at 8 Gb tRFC = matches the model
#
# UberDDR3 ships only the 8 Gb Micron parameter set, so the DDR3 model is 8 Gb
# either way.  SDRAM_CAPACITY feeds exactly one localparam in ddr3_controller.v
# (tRFC) and the refresh stall we measure is generated by the controller, not the
# model - so the default run reproduces the real part's refresh cost exactly.
# It also makes the 8 Gb model emit "tRFC violation during Activate" errors, which
# are expected: that is the mismatch talking.  Data is checked on every read, so a
# violation that actually corrupted data would show up as a data error.
set -euo pipefail

defines="-DSIM_MODEL -DNO_TEST_MODEL"
if [ "${1:-}" = "--model-density" ]; then
  defines="$defines -DMODEL_DENSITY"
  echo "controller tRFC: 350 ns (8 Gb, self-consistent with the model)"
else
  echo "controller tRFC: 160 ns (2 Gb, the real MT41K128M16JT-125)"
  echo "expect 'tRFC violation' errors from the 8 Gb model - see header"
fi

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
uber="$root/third_party/UberDDR3"
tb="$uber/testbench"

if [ ! -d "$uber/rtl" ]; then
  echo "UberDDR3 not fetched; running third_party/fetch_uberddr3.sh" >&2
  "$root/third_party/fetch_uberddr3.sh"
fi

out="$root/sim/latency_tb.out"

# -DSIM_MODEL swaps the Xilinx primitives in ddr3_phy.v for the behavioural
# models under testbench/models/.  -DNO_TEST_MODEL drops upstream's own harness.
iverilog -g2012 -o "$out" -s latency_tb \
    $defines \
    -I "$tb" \
    "$root/sim/latency_tb.sv" \
    "$tb/ddr3.sv" \
    "$tb/models/IDELAYCTRL_model.v" \
    "$tb/models/IDELAYE2_model.v" \
    "$tb/models/IOBUF_DCIEN_model.v" \
    "$tb/models/IOBUF_model.v" \
    "$tb/models/IOBUFDS_DCIEN_model.v" \
    "$tb/models/IOBUFDS_model.v" \
    "$tb/models/ISERDESE2_model.v" \
    "$tb/models/OBUFDS_model.v" \
    "$tb/models/ODELAYE2_model.v" \
    "$tb/models/OSERDESE2_model.v" \
    "$tb/models/OBUF_model.v" \
    "$uber/rtl/ddr3_top.v" \
    "$uber/rtl/ddr3_controller.v" \
    "$uber/rtl/ddr3_phy.v"

exec vvp -n "$out"
