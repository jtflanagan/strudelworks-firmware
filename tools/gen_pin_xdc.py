"""Generate the per-board pin constraints from the connector-named sources.

  constr/pins/board.pins      -> constr/<board>/board.xdc
  constr/pins/ft601.pins      -> constr/<board>/ft601_pins.xdc
  constr/pins/apple_bus.pins  -> constr/<board>/apple_bus_pins.xdc

The sources name pins the way the carrier and the Ft+ are wired: by Alchitry
connector pin (A41, B33, ...) or on-board function (CLOCK, LED0, ...).  Those
names are the same on the Au V2 and the Pt V2 - the DF40 connectors are
interchangeable - and the FPGA ball behind each one comes from the board's
table in ref/ (tools/boards.py).  So the same three sources produce a correct
XDC for either board, and the Pt port is a lookup, not a transcription.

Source format, one directive per line:
    pin <port> <connector pin> [IOSTANDARD]     (IOSTANDARD defaults to LVCMOS33)
    # comment                                     (dropped)
    <anything else>                               (copied into the XDC verbatim)

Run with no arguments to (re)generate every board; --board to do one;
--check to verify the committed files are current (exit non-zero if not) and
that build/build.tcl's part table agrees with tools/boards.py.  build/build.sh
runs --check before every build.
"""

import argparse
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import boards  # noqa: E402

ROOT = boards.ROOT
SRC_DIR = ROOT / "constr" / "pins"
FILES = {
    "board.pins": "board.xdc",
    "ft601.pins": "ft601_pins.xdc",
    "apple_bus.pins": "apple_bus_pins.xdc",
}
HEADER = """\
# SPDX-License-Identifier: GPL-2.0-or-later
# SPDX-FileCopyrightText: 2026 jtflanagan
##############################################################################
# {title}
#
# GENERATED by tools/gen_pin_xdc.py from constr/pins/{src} and {table}
# - do not hand-edit.  Re-run `python3 tools/gen_pin_xdc.py` to regenerate,
# or `python3 tools/gen_pin_xdc.py --check` to verify.
##############################################################################

"""


def render(board_name, src_name):
    b = boards.board(board_name)
    table = boards.pin_table(board_name)
    out = [HEADER.format(title=b["title"], src=src_name, table=b["pins"])]
    for raw in (SRC_DIR / src_name).read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"pin\s+(\S+)\s+(\S+)(?:\s+(\S+))?$", line)
        if not m:
            out.append(raw.rstrip() + "\n")
            continue
        port, conn, std = m.group(1), m.group(2), m.group(3) or "LVCMOS33"
        if conn not in table:
            raise SystemExit(f"{src_name}: {conn!r} is not a pin of {board_name}")
        ball, bank = table[conn]
        note = ""
        if bank in b["mv_banks"]:
            note = f"  ;# {conn}: bank {bank} is the multi-voltage bank - VBSEL must select 3.3 V"
        port_ref = f"{{{port}}}" if "[" in port else port
        out.append(f"set_property PACKAGE_PIN {ball} [get_ports {port_ref}]{note}\n")
        out.append(f"set_property IOSTANDARD {std} [get_ports {port_ref}]\n")
    return "".join(out)


def check_build_tcl():
    """build/build.tcl and build/synth_ooc.tcl carry the part per board as a
    Tcl array; make sure it says what tools/boards.py says."""
    problems = []
    for tcl in ("build/build.tcl", "build/synth_ooc.tcl"):
        text = (ROOT / tcl).read_text()
        found = dict(re.findall(r"set board_part\((\w+)\)\s+(\S+)", text))
        for name, b in boards.BOARDS.items():
            if found.get(name) != b["part"]:
                problems.append(f"{tcl}: board_part({name}) is {found.get(name)}, boards.py says {b['part']}")
        m = re.search(r"set board\s+(\w+)\s*$", text, re.M)
        if not m or m.group(1) != boards.DEFAULT_BOARD:
            problems.append(f"{tcl}: default board is {m and m.group(1)}, boards.py says {boards.DEFAULT_BOARD}")
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", choices=list(boards.BOARDS), help="one board (default: all)")
    ap.add_argument("--check", action="store_true", help="verify, do not write")
    args = ap.parse_args()

    names = [args.board] if args.board else list(boards.BOARDS)
    problems = check_build_tcl()
    for name in names:
        outdir = boards.constr_dir(name)
        for src, dst in FILES.items():
            text = render(name, src)
            path = outdir / dst
            if args.check:
                if not path.exists():
                    problems.append(f"{path.relative_to(ROOT)} does not exist")
                elif path.read_text() != text:
                    problems.append(f"{path.relative_to(ROOT)} is stale")
            else:
                outdir.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
                print(f"wrote {path.relative_to(ROOT)}")
    for p in problems:
        print(f"MISMATCH: {p}", file=sys.stderr)
    if problems:
        print("re-run tools/gen_pin_xdc.py without --check", file=sys.stderr)
        return 1
    if args.check:
        print(f"pin constraints up to date for: {', '.join(names)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
