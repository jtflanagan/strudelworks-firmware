"""png_testdata - synthetic PNGs for the RISC-V PNG decoder's test
(apple/rvvm/guest/png.c, apple/rvvm/guest/ctests/png.c), written by this small
encoder so that every case is there on purpose: the three deflate block kinds
(zlib level 0 = stored, 1 = mostly fixed codes, 9 = dynamic), all five row
filters (cycled row by row), colour types 0/2/3/6, image data split over many
IDAT chunks, and one with a bad CRC.  Each comes with the FNV-1a 32 of the
RGB565 pixels a right decoder produces.

  tools/png_testdata.py > apple/rvvm/guest/ctests/png_data.h
"""
import struct
import zlib


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    return a if pa <= pb and pa <= pc else (b if pb <= pc else c)


def filter_rows(rows, bpp):
    out = bytearray()
    prior = bytes(len(rows[0]))
    for y, row in enumerate(rows):
        f = y % 5
        out.append(f)
        for i, v in enumerate(row):
            a = row[i - bpp] if i >= bpp else 0
            b = prior[i]
            c = prior[i - bpp] if i >= bpp else 0
            pred = (0, a, b, (a + b) >> 1, paeth(a, b, c))[f]
            out.append((v - pred) & 0xFF)
        prior = row
    return bytes(out)


def chunk(t, data, bad_crc=False):
    crc = zlib.crc32(t + data) & 0xFFFFFFFF
    if bad_crc:
        crc ^= 1
    return struct.pack(">I", len(data)) + t + data + struct.pack(">I", crc)


def png(w, h, color, pixels, level, idat_split=0, palette=None, bad_crc=False):
    bpp = {0: 1, 2: 3, 3: 1, 6: 4}[color]
    rows = [bytes(pixels[y * w * bpp:(y + 1) * w * bpp]) for y in range(h)]
    raw = filter_rows(rows, bpp)
    if level == "fixed":                        # fixed codes are zlib's choice unless forced
        c = zlib.compressobj(6, zlib.DEFLATED, 15, 9, zlib.Z_FIXED)
        z = c.compress(raw) + c.flush()
    else:
        z = zlib.compress(raw, level)
    out = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, color, 0, 0, 0))
    if palette:
        out += chunk(b"PLTE", bytes(palette))
    if idat_split:
        for i in range(0, len(z), idat_split):
            out += chunk(b"IDAT", z[i:i + idat_split])
    else:
        out += chunk(b"IDAT", z, bad_crc)
    return out + chunk(b"IEND", b"")


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def fnv(pix, color, palette):
    h = 0x811C9DC5
    step = {0: 1, 2: 3, 3: 1, 6: 4}[color]
    for i in range(0, len(pix), step):
        if color == 0:
            v = rgb565(pix[i], pix[i], pix[i])
        elif color == 3:
            k = pix[i]
            v = rgb565(palette[3 * k], palette[3 * k + 1], palette[3 * k + 2])
        else:
            v = rgb565(pix[i], pix[i + 1], pix[i + 2])
        for byte in (v & 0xFF, v >> 8):
            h = ((h ^ byte) * 0x01000193) & 0xFFFFFFFF
    return h


def image(w, h, color, seed):
    bpp = {0: 1, 2: 3, 3: 1, 6: 4}[color]
    pix = bytearray()
    for y in range(h):
        for x in range(w):
            for k in range(bpp):
                # smooth gradients (so the filters matter) with some noise
                v = (x * (3 + k) + y * (5 + seed) + ((x * y + k * 7 + seed) * 2654435761 >> 13) % 23) & 0xFF
                pix.append(v if color != 3 else v % 40)
    return bytes(pix)


def main():
    pal = [((i * 37) & 0xFF, (i * 91) & 0xFF, (255 - i * 5) & 0xFF)[k] for i in range(40) for k in range(3)]
    cases = [
        ("rgb_stored", 37, 23, 2, 0, 0, None, False),
        ("rgb_fixed", 40, 30, 2, "fixed", 0, None, False),
        ("rgba_dynamic", 33, 29, 6, 9, 0, None, False),
        ("grey_dynamic", 48, 31, 0, 9, 0, None, False),
        ("palette_split", 45, 27, 3, 9, 61, pal, False),
        ("bad_crc", 16, 8, 2, 6, 0, None, True),
    ]
    print("/* generated by tools/png_testdata.py - do not edit */")
    names = []
    for i, (name, w, h, color, level, split, palette, bad) in enumerate(cases):
        pix = image(w, h, color, i)
        data = png(w, h, color, pix, level, split, palette, bad)
        want = fnv(pix, color, palette)
        body = ", ".join(str(b) for b in data)
        print(f"static const unsigned char png_{name}[{len(data)}] = {{{body}}};")
        names.append((name, len(data), w, h, 3 if bad else 0, want))
    print("static const struct png_case { const unsigned char *data; unsigned n, w, h; int err; unsigned fnv; } png_cases[] = {")
    for name, n, w, h, err, want in names:
        print(f"    {{png_{name}, {n}, {w}, {h}, {err}, 0x{want:08X}u}},")
    print("};")


if __name__ == "__main__":
    main()
