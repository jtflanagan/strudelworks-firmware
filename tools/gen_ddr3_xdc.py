"""Generate constr/<board>/ddr3.xdc from the board's MIG project file, and
verify it against every independent record of the same pinout we have.

We are NOT using the MIG core, but the MIG *pin assignment* for each Alchitry
board's DDR3 is still the authoritative record of how that board wires bank 15
to its MT41K128M16JT-125.  So this script re-emits exactly those pin
constraints under our own top-level port names, and drops everything
MIG-internal (PHASER / OUT_FIFO / PLLE2 LOCs, MIG timing exceptions) which
would not resolve against UberDDR3's hierarchy.

Inputs, per board (tools/boards.py):
  ref/mig_a.prj        Au V2  - the v5 MIG GUI settings, incl. <PinSelection>
  ref/mig_pt_v2.prj    Pt V2  - Alchitry Labs V2's library/cores/mig_pt_v2.prj,
                                identical to its Au V2 project but for the
                                part and the pins (checked 2026-09-03)
  ref/mig_7series_0.generated.xdc  - what MIG emitted for the Au, cross-check only
  ref/alchitry_*_pins.tsv          - Alchitry Labs V2's own DDR_* pin table,
                                     cross-checked for every board

Output:
  constr/<board>/ddr3.xdc

Run with --check to verify the committed XDCs still match (exit non-zero if
not).  No --board means every board.
"""

import argparse
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import boards  # noqa: E402

ROOT = boards.ROOT

# Bank the DDR3 sits in, on both boards.  MIG emitted `INTERNAL_VREF 0.675` for
# this bank and nothing else, which is how we know it is the only one involved;
# the Labs pin tables put every DDR_* pin in bank 15 on the Pt V2 too.
DDR3_BANK = 15
INTERNAL_VREF = 0.675  # half of 1.35 V (SSTL135 / DDR3L)

# Order the pins are emitted in.  Purely cosmetic, but keeps the diff stable.
GROUP_ORDER = [
    "ddr3_dq",
    "ddr3_dqs_p",
    "ddr3_dqs_n",
    "ddr3_dm",
    "ddr3_addr",
    "ddr3_ba",
    "ddr3_ras_n",
    "ddr3_cas_n",
    "ddr3_we_n",
    "ddr3_cs_n",
    "ddr3_cke",
    "ddr3_odt",
    "ddr3_ck_p",
    "ddr3_ck_n",
    "ddr3_reset_n",
]

HEADER = """\
# SPDX-License-Identifier: GPL-2.0-or-later
# SPDX-FileCopyrightText: 2026 jtflanagan
##############################################################################
# DDR3 pin constraints - {title} + MT41K128M16JT-125
#
# GENERATED by tools/gen_ddr3_xdc.py from {prj} - do not hand-edit.
# Re-run `python3 tools/gen_ddr3_xdc.py` to regenerate,
# or `python3 tools/gen_ddr3_xdc.py --check` to verify.
#
# Port names here are the MIG/v5 top-level names, NOT UberDDR3's internal ones.
# rtl/common/ddr3_wrapper.sv does the rename (ddr3_ck_* -> o_ddr3_clk_*, ddr3_ba ->
# o_ddr3_ba_addr, and the o_/io_ prefixes).  Keeping the MIG names at the pin
# boundary means this file is a pin-for-pin transcription of a constraint set
# that is known to have worked on this exact board.
#
# Deliberately NOT carried over from the MIG-generated XDC:
#   - IO_BUFFER_TYPE NONE on ddr3_ck_p/n.  MIG drives CK from inside its own PHY
#     with the buffer already placed; UberDDR3's ddr3_phy.v instantiates an
#     OBUFDS itself and expects Vivado to leave the port alone.  The Arty-S7
#     reference XDC for UberDDR3 does not set it either.
#   - All PHASER_* / OUT_FIFO / IN_FIFO / PHY_CONTROL / PLLE2 / MMCME2 LOCs and
#     the MIG timing exceptions - those name MIG hierarchy that does not exist
#     here.  UberDDR3 lets the placer pick, so byte-lane placement is a risk to
#     watch during the first build (see docs/DERISK.md).
##############################################################################

"""

# MIG port name -> Alchitry Labs pin-table name, for the cross-check.
LABS_NAMES = {
    "addr": "DDR_A{i}", "ba": "DDR_BA{i}", "dq": "DDR_DQ{i}", "dm": "DDR_DM{i}",
    "dqs_p": "DDR_DQS{i}_P", "dqs_n": "DDR_DQS{i}_N",
    "ck_p": "DDR_CK_P", "ck_n": "DDR_CK_N", "cke": "DDR_CKE", "cs_n": "DDR_CS",
    "odt": "DDR_ODT", "ras_n": "DDR_RAS", "cas_n": "DDR_CAS", "we_n": "DDR_WE",
    "reset_n": "DDR_RESET",
}


def parse_prj(path):
    """-> list of (port_name, package_pin, iostandard, slew, in_term)."""
    root = ET.parse(path).getroot()
    pins = []
    for pin in root.iter("Pin"):
        name = pin.get("name")
        pad = pin.get("PADName")
        if not name or not pad or pad == "No connect":
            continue
        pins.append(
            (
                name,
                pad,
                pin.get("IOSTANDARD") or "",
                pin.get("SLEW") or "",
                pin.get("IN_TERM") or "",
            )
        )
    return pins


def sort_key(name):
    m = re.match(r"^(.*?)(?:\[(\d+)\])?$", name)
    base, idx = m.group(1), int(m.group(2) or 0)
    try:
        group = GROUP_ORDER.index(base)
    except ValueError:
        group = len(GROUP_ORDER)
    return (group, base, idx)


def render(board_name, pins):
    b = boards.board(board_name)
    out = [HEADER.format(title=b["title"], prj=b["mig_prj"])]
    last_base = None
    for name, pad, iostd, slew, in_term in sorted(
        pins, key=lambda p: sort_key(p[0])
    ):
        base = re.sub(r"\[\d+\]$", "", name)
        if base != last_base:
            out.append(f"# ---- {base} ----\n")
            last_base = base
        out.append(f"set_property PACKAGE_PIN {pad} [get_ports {{{name}}}]\n")
        if iostd:
            out.append(f"set_property IOSTANDARD {iostd} [get_ports {{{name}}}]\n")
        if slew:
            out.append(f"set_property SLEW {slew} [get_ports {{{name}}}]\n")
        if in_term:
            out.append(f"set_property IN_TERM {in_term} [get_ports {{{name}}}]\n")
    out.append(
        "\n# ---- bank properties ----\n"
        "# Bank 15 is an HR bank (Artix-7 has no HP banks in any package), so\n"
        "# there is no DCI: termination is the UNTUNED_SPLIT_50 above, and VREF has\n"
        "# to come from the internal reference.  This also forces\n"
        "# ODELAY_SUPPORTED = 0 in the UberDDR3 instance, which is why the design\n"
        "# needs a 90-degree-shifted DDR3 clock (see rtl/common/clk_gen.v).\n"
        f"set_property INTERNAL_VREF {INTERNAL_VREF} [get_iobanks {DDR3_BANK}]\n"
    )
    return "".join(out)


def labs_name(port):
    m = re.match(r"ddr3_(\w+?)(?:\[(\d+)\])?$", port)
    return LABS_NAMES[m.group(1)].format(i=m.group(2) or "")


def cross_check(board_name, pins):
    """Confirm every PACKAGE_PIN we emit matches the other records we hold:
    the MIG-generated XDC where there is one, and Alchitry Labs' pin table."""
    b = boards.board(board_name)
    problems = []
    ours = {name: pad for name, pad, *_ in pins}

    table = boards.pin_table(board_name)
    for name, pad in sorted(ours.items()):
        labs = table.get(labs_name(name))
        if labs is None:
            problems.append(f"{name}: no {labs_name(name)} in {b['pins']}")
        elif labs[0] != pad:
            problems.append(f"{name}: .prj says {pad}, {b['pins']} says {labs[0]}")
        elif labs[1] != DDR3_BANK:
            problems.append(f"{name}: {b['pins']} puts it in bank {labs[1]}, not {DDR3_BANK}")

    if not b["mig_xdc"]:
        return problems
    text = (ROOT / b["mig_xdc"]).read_text()
    mig = {}
    # Note the port name may itself contain brackets (ddr3_dq[0]), so match the
    # braced form specifically rather than anything-up-to-a-bracket.
    for m in re.finditer(
        r"set_property\s+PACKAGE_PIN\s+(\S+)\s+\[\s*get_ports\s+"
        r"(?:\{\s*([^\}]+?)\s*\}|([A-Za-z_]\w*))\s*\]",
        text,
    ):
        mig[m.group(2) or m.group(3)] = m.group(1)
    for name, pad in sorted(ours.items()):
        if name not in mig:
            problems.append(f"{name}: present in .prj but not in MIG xdc")
        elif mig[name] != pad:
            problems.append(f"{name}: .prj says {pad}, MIG xdc says {mig[name]}")
    for name in sorted(set(mig) - set(ours)):
        problems.append(f"{name}: in MIG xdc but not emitted")
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", choices=list(boards.BOARDS), help="one board (default: all)")
    ap.add_argument("--check", action="store_true", help="verify, do not write")
    args = ap.parse_args()

    names = [args.board] if args.board else list(boards.BOARDS)
    rc = 0
    for name in names:
        b = boards.board(name)
        pins = parse_prj(ROOT / b["mig_prj"])
        problems = cross_check(name, pins)
        for p in problems:
            print(f"MISMATCH [{name}]: {p}", file=sys.stderr)
        if problems:
            rc = 1
            continue
        print(f"[{name}] cross-check OK: {len(pins)} pins agree with {b['pins']}"
              + (" and the MIG-generated XDC" if b["mig_xdc"] else ""))

        text = render(name, pins)
        out = boards.constr_dir(name) / "ddr3.xdc"
        if args.check:
            if not out.exists():
                print(f"{out} does not exist", file=sys.stderr)
                rc = 1
            elif out.read_text() != text:
                print(f"{out} is stale - re-run without --check", file=sys.stderr)
                rc = 1
            else:
                print(f"{out.relative_to(ROOT)} is up to date")
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"wrote {out.relative_to(ROOT)}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
