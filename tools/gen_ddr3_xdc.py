"""Generate constr/ddr3.xdc from the MIG project file, and verify it against the
XDC that MIG itself generated.

We are NOT using the MIG core, but the MIG *pin assignment* for the Alchitry Au's
DDR3 is still the authoritative record of how the Au wires xc7a35t-ftg256 bank 15
to its MT41K128M16JT-125.  So this script re-emits exactly those pin constraints
under our own top-level port names, and drops everything MIG-internal (PHASER /
OUT_FIFO / PLLE2 LOCs, MIG timing exceptions) which would not resolve against
UberDDR3's hierarchy.

Inputs (both copied into ref/ from ~/repos/AppleTini/v5, see docs/DERISK.md):
  ref/mig_a.prj                    - the MIG GUI settings, incl. <PinSelection>
  ref/mig_7series_0.generated.xdc  - what MIG emitted, used only as a cross-check

Output:
  constr/ddr3.xdc

Run with --check to verify the committed XDC still matches (exit non-zero if not).
"""

import argparse
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
PRJ = ROOT / "ref" / "mig_a.prj"
MIG_XDC = ROOT / "ref" / "mig_7series_0.generated.xdc"
OUT = ROOT / "constr" / "ddr3.xdc"

# Bank the DDR3 sits in on the Au.  MIG emitted `INTERNAL_VREF 0.675` for this
# bank and nothing else, which is how we know it is the only one involved.
DDR3_BANK = 15
INTERNAL_VREF = 0.675  # half of 1.35 V (SSTL135 / DDR3L)

# Order the pins are emitted in.  Purely cosmetic, but keeps the diff stable.
GROUP_ORDER = [
    "ddr3_dq",
    "ddr3_dqs_p",
    "ddr3_dqs_n",
    "ddr3_dm",
    "ddr3_addr",
    "ddr3_ba",
    "ddr3_ras_n",
    "ddr3_cas_n",
    "ddr3_we_n",
    "ddr3_cs_n",
    "ddr3_cke",
    "ddr3_odt",
    "ddr3_ck_p",
    "ddr3_ck_n",
    "ddr3_reset_n",
]

HEADER = """\
# SPDX-License-Identifier: BSD-2-Clause
# SPDX-FileCopyrightText: 2026 jtflanagan
##############################################################################
# DDR3 pin constraints - Alchitry Au (xc7a35t-ftg256-2) + MT41K128M16JT-125
#
# GENERATED by tools/gen_ddr3_xdc.py from ref/mig_a.prj - do not hand-edit.
# Re-run `python3 tools/gen_ddr3_xdc.py` to regenerate,
# or `python3 tools/gen_ddr3_xdc.py --check` to verify.
#
# Port names here are the MIG/v5 top-level names, NOT UberDDR3's internal ones.
# rtl/ddr3_wrapper.sv does the rename (ddr3_ck_* -> o_ddr3_clk_*, ddr3_ba ->
# o_ddr3_ba_addr, and the o_/io_ prefixes).  Keeping the MIG names at the pin
# boundary means this file is a pin-for-pin transcription of a constraint set
# that is known to have worked on this exact board.
#
# Deliberately NOT carried over from the MIG-generated XDC:
#   - IO_BUFFER_TYPE NONE on ddr3_ck_p/n.  MIG drives CK from inside its own PHY
#     with the buffer already placed; UberDDR3's ddr3_phy.v instantiates an
#     OBUFDS itself and expects Vivado to leave the port alone.  The Arty-S7
#     reference XDC for UberDDR3 does not set it either.
#   - All PHASER_* / OUT_FIFO / IN_FIFO / PHY_CONTROL / PLLE2 / MMCME2 LOCs and
#     the MIG timing exceptions - those name MIG hierarchy that does not exist
#     here.  UberDDR3 lets the placer pick, so byte-lane placement is a risk to
#     watch during the first build (see docs/DERISK.md).
##############################################################################

"""


def parse_prj(path):
    """-> list of (port_name, package_pin, iostandard, slew, in_term)."""
    root = ET.parse(path).getroot()
    pins = []
    for pin in root.iter("Pin"):
        name = pin.get("name")
        pad = pin.get("PADName")
        if not name or not pad or pad == "No connect":
            continue
        pins.append(
            (
                name,
                pad,
                pin.get("IOSTANDARD") or "",
                pin.get("SLEW") or "",
                pin.get("IN_TERM") or "",
            )
        )
    return pins


def sort_key(name):
    m = re.match(r"^(.*?)(?:\[(\d+)\])?$", name)
    base, idx = m.group(1), int(m.group(2) or 0)
    try:
        group = GROUP_ORDER.index(base)
    except ValueError:
        group = len(GROUP_ORDER)
    return (group, base, idx)


def render(pins):
    out = [HEADER]
    last_base = None
    for name, pad, iostd, slew, in_term in sorted(
        pins, key=lambda p: sort_key(p[0])
    ):
        base = re.sub(r"\[\d+\]$", "", name)
        if base != last_base:
            out.append(f"# ---- {base} ----\n")
            last_base = base
        out.append(f"set_property PACKAGE_PIN {pad} [get_ports {{{name}}}]\n")
        if iostd:
            out.append(f"set_property IOSTANDARD {iostd} [get_ports {{{name}}}]\n")
        if slew:
            out.append(f"set_property SLEW {slew} [get_ports {{{name}}}]\n")
        if in_term:
            out.append(f"set_property IN_TERM {in_term} [get_ports {{{name}}}]\n")
    out.append(
        "\n# ---- bank properties ----\n"
        "# Bank 15 is an HR bank (the ftg256 xc7a35t has no HP banks at all), so\n"
        "# there is no DCI: termination is the UNTUNED_SPLIT_50 above, and VREF has\n"
        "# to come from the internal reference.  This also forces\n"
        "# ODELAY_SUPPORTED = 0 in the UberDDR3 instance, which is why the design\n"
        "# needs a 90-degree-shifted DDR3 clock (see rtl/clk_gen.v).\n"
        f"set_property INTERNAL_VREF {INTERNAL_VREF} [get_iobanks {DDR3_BANK}]\n"
    )
    return "".join(out)


def cross_check(pins):
    """Confirm every PACKAGE_PIN we emit matches the MIG-generated XDC."""
    if not MIG_XDC.exists():
        return [f"{MIG_XDC} missing - skipping cross-check"]
    text = MIG_XDC.read_text()
    mig = {}
    # Note the port name may itself contain brackets (ddr3_dq[0]), so match the
    # braced form specifically rather than anything-up-to-a-bracket.
    for m in re.finditer(
        r"set_property\s+PACKAGE_PIN\s+(\S+)\s+\[\s*get_ports\s+"
        r"(?:\{\s*([^\}]+?)\s*\}|([A-Za-z_]\w*))\s*\]",
        text,
    ):
        mig[m.group(2) or m.group(3)] = m.group(1)
    problems = []
    ours = {name: pad for name, pad, *_ in pins}
    for name, pad in sorted(ours.items()):
        if name not in mig:
            problems.append(f"{name}: present in .prj but not in MIG xdc")
        elif mig[name] != pad:
            problems.append(f"{name}: .prj says {pad}, MIG xdc says {mig[name]}")
    for name in sorted(set(mig) - set(ours)):
        problems.append(f"{name}: in MIG xdc but not emitted")
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify, do not write")
    args = ap.parse_args()

    pins = parse_prj(PRJ)
    problems = cross_check(pins)
    for p in problems:
        print(f"MISMATCH: {p}", file=sys.stderr)
    if problems:
        return 1
    print(f"cross-check OK: {len(pins)} pins agree with the MIG-generated XDC")

    text = render(pins)
    if args.check:
        if not OUT.exists():
            print(f"{OUT} does not exist", file=sys.stderr)
            return 1
        if OUT.read_text() != text:
            print(f"{OUT} is stale - re-run without --check", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
