"""adb_ascii_h - the ADB micro's plain column (rtl/gs/adb_keymap.hex, from KEGS's
table by tools/gen_adb_keymap.py) as a C table for RISC-V programs that take raw
ADB keycodes (librvgs's rvgs_adb_event): keycode -> the unshifted ASCII byte, 0
for a key with none or a special one (a modifier, a function key).  So a program
and the card's own keyboard agree on what a keycode is.

  tools/adb_ascii_h.py [rtl/gs/adb_keymap.hex] > adb_ascii.h
"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "rtl", "gs", "adb_keymap.hex")
rows = [int(line.strip(), 16) for line in open(path) if line.strip() and not line.startswith("//")]
if len(rows) != 128:
    sys.exit(f"{path}: {len(rows)} entries, want 128")
out = []
for v in rows:
    plain = v & 0x3FF                     # {none, special, byte}
    out.append(0 if plain & 0x300 else plain & 0xFF)
print("/* generated by tools/adb_ascii_h.py from rtl/gs/adb_keymap.hex - do not edit */")
print("static const unsigned char adb_ascii[128] = {")
for i in range(0, 128, 16):
    print("    " + ", ".join(f"0x{b:02X}" for b in out[i:i + 16]) + ",")
print("};")
